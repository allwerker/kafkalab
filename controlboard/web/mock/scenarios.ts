const d = (title: string, uid: string) => ({ title, url: dashboardUrl(uid) });
const CONSUMERS = ["payment", "inventory", "shipping", "notification", "analytics"];

const serviceParam = (def: string): ScenarioParam => ({
  key: "service",
  label: "Target service",
  type: "service",
  options: CONSUMERS,
  default: def,
});
const brokerParam = (key = "broker", label = "Broker", def = 1): ScenarioParam => ({
  key,
  label,
  type: "broker",
  options: ["0", "1", "2"],
  default: def,
});
const num = (key: string, label: string, def: number, min: number, max: number, step: number, unit?: string): ScenarioParam => ({
  key,
  label,
  type: "number",
  min,
  max,
  step,
  default: def,
  ...(unit ? { unit } : {}),
});

